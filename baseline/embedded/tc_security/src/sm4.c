static uint32_t read_u32_be(const uint8_t value[4]) {
    return ((uint32_t)value[0] << 24) | ((uint32_t)value[1] << 16) |
           ((uint32_t)value[2] << 8) | (uint32_t)value[3];
}

static void write_u32_be(uint8_t output[4], uint32_t value) {
    output[0] = (uint8_t)(value >> 24);
    output[1] = (uint8_t)(value >> 16);
    output[2] = (uint8_t)(value >> 8);
    output[3] = (uint8_t)value;
}

static uint32_t rotate_left(uint32_t value, uint8_t count) {
    return (value << count) | (value >> (32u - count));
}

static uint32_t substitute(uint32_t value) {
    return ((uint32_t)sbox[(value >> 24) & 0xffu] << 24) |
           ((uint32_t)sbox[(value >> 16) & 0xffu] << 16) |
           ((uint32_t)sbox[(value >> 8) & 0xffu] << 8) |
           (uint32_t)sbox[value & 0xffu];
}

static uint32_t round_transform(uint32_t value) {
    uint32_t transformed = substitute(value);
    return transformed ^ rotate_left(transformed, 2u) ^ rotate_left(transformed, 10u) ^
           rotate_left(transformed, 18u) ^ rotate_left(transformed, 24u);
}

static uint32_t key_transform(uint32_t value) {
    uint32_t transformed = substitute(value);
    return transformed ^ rotate_left(transformed, 13u) ^ rotate_left(transformed, 23u);
}

static void zero_memory(void *memory, size_t length) {
    volatile uint8_t *cursor = (volatile uint8_t *)memory;
    while (length-- != 0u) {
        *cursor++ = 0u;
    }
}

static void expand_key(const uint8_t key[16], uint32_t round_keys[32]) {
    uint32_t state[36];
    uint32_t round;
    state[0] = read_u32_be(&key[0]) ^ fk[0];
    state[1] = read_u32_be(&key[4]) ^ fk[1];
    state[2] = read_u32_be(&key[8]) ^ fk[2];
    state[3] = read_u32_be(&key[12]) ^ fk[3];
    for (round = 0u; round < 32u; ++round) {
        state[round + 4u] = state[round] ^ key_transform(
            state[round + 1u] ^ state[round + 2u] ^ state[round + 3u] ^ ck[round]);
        round_keys[round] = state[round + 4u];
    }
    zero_memory(state, sizeof(state));
}

static void crypt_block(const uint8_t input[16], uint8_t output[16],
                        const uint32_t round_keys[32], int decrypt) {
    uint32_t state[36];
    uint32_t round;
    state[0] = read_u32_be(&input[0]);
    state[1] = read_u32_be(&input[4]);
    state[2] = read_u32_be(&input[8]);
    state[3] = read_u32_be(&input[12]);
    for (round = 0u; round < 32u; ++round) {
        state[round + 4u] = state[round] ^ round_transform(
            state[round + 1u] ^ state[round + 2u] ^ state[round + 3u] ^
            round_keys[decrypt != 0 ? 31u - round : round]);
    }
    write_u32_be(&output[0], state[35]);
    write_u32_be(&output[4], state[34]);
    write_u32_be(&output[8], state[33]);
    write_u32_be(&output[12], state[32]);
    zero_memory(state, sizeof(state));
}

int tcsec_sm4_key_init(tcsec_sm4_key_t *context, const uint8_t key[16]) {
    if (context == NULL || key == NULL) return -1;
    expand_key(key, context->round_keys);
    return 0;
}

void tcsec_sm4_key_clear(tcsec_sm4_key_t *context) {
    if (context != NULL) zero_memory(context, sizeof(*context));
}

void tcsec_sm4_encrypt_with_key(const tcsec_sm4_key_t *context,
                                const uint8_t input[16], uint8_t output[16]) {
    crypt_block(input, output, context->round_keys, 0);
}

void tcsec_sm4_decrypt_with_key(const tcsec_sm4_key_t *context,
                                const uint8_t input[16], uint8_t output[16]) {
    crypt_block(input, output, context->round_keys, 1);
}

int tcsec_sm4_encrypt_block(const uint8_t key[16],
                            const uint8_t input[16],
                            uint8_t output[16]) {
    uint32_t round_keys[32];
    if (key == NULL || input == NULL || output == NULL) {
        return -1;
    }
    expand_key(key, round_keys);
    crypt_block(input, output, round_keys, 0);
    zero_memory(round_keys, sizeof(round_keys));
    return 0;
}
