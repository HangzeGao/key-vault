static void zeroize(void *memory, size_t length) {
    volatile uint8_t *cursor = (volatile uint8_t *)memory;
    while (length-- != 0u) *cursor++ = 0u;
}

int tcsec_crypto_self_test(tcsec_crypto_backend_t *backend) {
    static const uint8_t sm4_key[16] = {
        0x01,0x23,0x45,0x67,0x89,0xab,0xcd,0xef,
        0xfe,0xdc,0xba,0x98,0x76,0x54,0x32,0x10
    };
    static const uint8_t sm4_expected[16] = {
        0x68,0x1e,0xdf,0x34,0xd2,0x06,0x96,0x5e,
        0x86,0xb3,0xe9,0x4f,0x53,0x6e,0x42,0x46
    };
    static const uint8_t hctr_expected[21] = {
        0x26,0x3d,0x34,0x2e,0x86,0xdc,0x6e,0xff,0x82,0x0c,0x59,
        0xdb,0xf9,0xf1,0xa9,0x4f,0xcb,0x9d,0xe4,0x64,0xc1
    };
    static const uint8_t hctr_plaintext[21] = {
        0xca,0xfe,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x09,
        0x0a,0x0b,0x0c,0x0d,0x0e,0x0f,0x10,0x11,0x12,0x13
    };
    static const uint8_t recovery_frame[70] = {
        0x20,0x01,0x00,0x45,0x01,0x70,0x02,0x01,0x02,0x03,0x04,
        0xc4,0x87,0x88,0xc3,0xe5,0xb5,0xdf,0xab,0x05,0x3d,0xc5,
        0xd2,0xb1,0x30,0xbd,0x7c,0x30,0xb7,0x17,0x20,0x41,0x72,
        0x26,0xe5,0x41,0xd0,0x24,0xf6,0x21,0xb8,0xca,0x0e,0x60,
        0xe6,0xe6,0x10,0x4f,0x77,0x03,0xc5,0x03,0x69,0xf8,0x7c,
        0xdc,0xb4,0x69,0xa5,0x04,0xa6,0xf5,0xf8,0x3e,0xec,0xdd,
        0x10,0x8f,0x48,0xbe
    };
    static const uint8_t recovery_plaintext[41] = {
        0x01,0x01,0x02,0x03,0x04,0x05,0x06,0x07,0x08,0x00,0x00,
        0x00,0x07,0x00,0x00,0x00,0x08,0x00,0x00,0x00,0x09,0x20,
        0x02,0x00,0x13,0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff
    };
    uint8_t output[41];
    uint8_t working_key[TCSEC_HCTR_WORKING_KEY_LENGTH];
    uint8_t recovery_key[TCSEC_SM4_KEY_LENGTH];
    uint8_t tweak[TCSEC_HCTR_TWEAK_LENGTH] = {
        0xa1,0xa2,0xa3,0xa4,0xa5,0xa6,0x20,0x02,0x00,0x00,0x00,0x09,0,0,0,0
    };
    uint8_t nonce[TCSEC_GCM_NONCE_LENGTH] = {
        0xb0,0xb1,0xb2,0xb3,0xb4,0xb5,0x70,0x02,0x01,0x02,0x03,0x04
    };
    tcsec_sm4_key_t key_context;
    int result = -1;
    if (backend == NULL || tcsec_sm4_key_init(&key_context, sm4_key) != 0) return -1;
    *backend = (tcsec_crypto_backend_t)tcsec_sm4_backend_id(&key_context);
    tcsec_sm4_encrypt_with_key(&key_context, sm4_key, output);
    if (memcmp(output, sm4_expected, sizeof(sm4_expected)) != 0) goto cleanup;
    tcsec_sm4_decrypt_with_key(&key_context, output, output);
    if (memcmp(output, sm4_key, sizeof(sm4_key)) != 0) goto cleanup;
    if (tcsec_derive_ordinary_key(sm4_key, sizeof(sm4_key), 0x1234u,
                                  TCSEC_SUITE_SM4_HCTR, 0x2002u, 7u, 9u,
                                  working_key, sizeof(working_key)) != 0 ||
        tcsec_sm4_hctr_encrypt(working_key, tweak, hctr_plaintext, output,
                              sizeof(hctr_plaintext)) != 0 ||
        memcmp(output, hctr_expected, sizeof(hctr_expected)) != 0) goto cleanup;
    if (tcsec_derive_recovery_key(sm4_key, sizeof(sm4_key), 0x1234u,
                                  TCSEC_SUITE_SM4_GCM, 0x7002u, 3u,
                                  recovery_key, sizeof(recovery_key)) != 0 ||
        tcsec_gcm_open(TCSEC_SUITE_SM4_GCM, recovery_key, nonce, recovery_frame, 11u,
                       &recovery_frame[11], 41u, &recovery_frame[52], output) != 0 ||
        memcmp(output, recovery_plaintext, sizeof(recovery_plaintext)) != 0) goto cleanup;
#if defined(TCSEC_TEST_SELF_TEST_FAILURE)
    goto cleanup;
#else
    result = 0;
#endif
cleanup:
    tcsec_sm4_key_clear(&key_context);
    zeroize(output, sizeof(output));
    zeroize(working_key, sizeof(working_key));
    zeroize(recovery_key, sizeof(recovery_key));
    return result;
}
