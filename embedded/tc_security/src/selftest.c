int tcsec_crypto_self_test(tcsec_crypto_backend_t *backend) {
    tcsec_sm4_key_t context;
    uint8_t output[41], key[16], bad_tag[16];
    int result = -1;
    if (backend == NULL || tcsec_sm4_key_init(&context, root) != 0)
        return -1;
    *backend = (tcsec_crypto_backend_t)tcsec_sm4_backend_id(&context);
    tcsec_sm4_encrypt_with_key(&context, root, output);
    if (memcmp(output, sm4_expected, 16) != 0)
        goto cleanup;
    tcsec_sm4_decrypt_with_key(&context, output, output);
    if (memcmp(output, root, 16) != 0)
        goto cleanup;
    if (tcsec_derive_ordinary_key(root, 16, 0x1234, TCSEC_SUITE_SM4_GCM_32, 0x2001, 7, 9, key,
                                  16) != 0 ||
        memcmp(key, kdf_expected, 16) != 0)
        goto cleanup;
    if (tcsec_derive_ordinary_key(root, 16, 1, TCSEC_SUITE_SM4_GCM_32, 8194, 7, 9, key, 16) != 0 ||
        tcsec_gcm_open_short(key, ordinary_nonce, ordinary_frame, 7, ordinary_frame + 11,
                             sizeof(ordinary_plain), ordinary_frame + 7, output) != 0 ||
        memcmp(output, ordinary_plain, sizeof(ordinary_plain)) != 0)
        goto cleanup;
    if (tcsec_derive_recovery_key(root, 16, 1, TCSEC_SUITE_SM4_GCM, 28674, 3, key, 16) != 0 ||
        tcsec_gcm_open(TCSEC_SUITE_SM4_GCM, key, recovery_nonce, recovery_frame, 11,
                       recovery_frame + 11, sizeof(recovery_plain),
                       recovery_frame + 11 + sizeof(recovery_plain), output) != 0 ||
        memcmp(output, recovery_plain, sizeof(recovery_plain)) != 0)
        goto cleanup;
    memcpy(bad_tag, recovery_frame + 11 + sizeof(recovery_plain), 16);
    bad_tag[0] ^= 1u;
    if (tcsec_gcm_open(TCSEC_SUITE_SM4_GCM, key, recovery_nonce, recovery_frame, 11,
                       recovery_frame + 11, sizeof(recovery_plain), bad_tag, output) == 0)
        goto cleanup;
#if !defined(TCSEC_TEST_SELF_TEST_FAILURE)
    result = 0;
#endif
cleanup:
    tcsec_sm4_key_clear(&context);
    zeroize(output, sizeof(output));
    zeroize(key, sizeof(key));
    zeroize(bad_tag, sizeof(bad_tag));
    return result;
}
